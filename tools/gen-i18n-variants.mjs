function applyList(text, list) {
    const ordered = list.slice().sort((a, b) => b[0].length - a[0].length);
    const placeholders = [];
    for (const [from, to] of ordered) {
        if (!from || !text.includes(from)) continue;
        const token = `\u0000${placeholders.length}\u0000`;
        text = text.split(from).join(token);
        placeholders.push(to);
    }
    for (let i = 0; i < placeholders.length; i++) {
        text = text.split(`\u0000${i}\u0000`).join(placeholders[i]);
    }
    return text;
}

function translate(desc, fam, pre, phrases) {
    const exact = fam.find(([from]) => from === desc);
    if (exact) return exact[1];
    const all = fam.concat(pre, phrases);
    const colon = desc.indexOf(': ');
    if (colon > 0) {
        const left = applyList(desc.slice(0, colon), all);
        const right = applyList(desc.slice(colon + 2), all);
        return left + ': ' + right;
    }
    return applyList(desc, all);
}

