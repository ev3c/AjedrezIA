import fs from 'fs';

const src = fs.readFileSync('app.js', 'utf8');
const start = src.indexOf('const OPENING_NAMES = {');
const end = src.indexOf('\n};\n', start);
const block = src.slice(start, end + 3);
const names = [];
const re = /'((?:\\'|[^'])*)':\s*'((?:\\'|[^'])*)'/g;
let m;
while ((m = re.exec(block))) {
    names.push({ key: m[1], raw: m[2].replace(/\\'/g, "'") });
}

function descOf(raw) {
    const i = raw.indexOf(' — ');
    return i >= 0 ? raw.slice(i + 3) : raw;
}

function slug(s) {
    return s.toLowerCase()
        .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
        .replace(/:/g, '.')
        .replace(/[^a-z0-9.]+/g, '-')
        .replace(/^[-.]+|[-.]+$/g, '');
}

const unique = new Map();
for (const { raw } of names) {
    const desc = descOf(raw);
    const key = 'var.' + slug(desc);
    if (!unique.has(key)) unique.set(key, desc);
    else if (unique.get(key) !== desc) {
        console.error('SLUG COLLISION', key, unique.get(key), desc);
        process.exit(1);
    }
}

